"""## CORRECCIÓN DE FASE

### Modificar la corrección de fase usando Chunking
"""

import librosa
import numpy as np
import soundfile as sf
import os
import gc # For garbage collection
import shutil # For copying files

# --- Chunking Parameters (Instruction 1) ---
chunk_duration_seconds = 30 # Process 30 seconds of audio at a time
n_fft = 2048 # FFT window size
hop_length = 512 # Hop length for STFT

# --- Define ARCHIVO_INPUT explicitly for this cell's execution context ---
ARCHIVO_INPUT = '/content/drive/MyDrive/Processed_Audio_Colab/MVSep Piano UI/piano-model-mt-5-piano-mvsep.wav'
LOCAL_TEMP_ORIGINAL_AUDIO_PATH = '/content/.temp_original_audiowav'
# ---------------------------------------------------------------------------

# --- Define Output Folder and Parameters (Moved from previous setup cell for robustness) ---
OUTPUT_FOLDER_PHASE_CORRECTIONS = "/content/drive/MyDrive/Processed_Audio_Colab/Phase_Corrections"
os.makedirs(OUTPUT_FOLDER_PHASE_CORRECTIONS, exist_ok=True)
PHASE_CORRECTION_PRIORITY_CHANNEL = 'L' # @param ['L', 'R']
# ---------------------------------------------------------------------------------------

if not os.path.exists(ARCHIVO_INPUT):
    print(f"❌ ERROR: The original audio file was not found at {ARCHIVO_INPUT}.")
    exit()

# --- Copy original file to a local Colab directory for robust access ---
print(f"Copiando el archivo original desde Google Drive a {LOCAL_TEMP_ORIGINAL_AUDIO_PATH}...")
try:
    shutil.copy(ARCHIVO_INPUT, LOCAL_TEMP_ORIGINAL_AUDIO_PATH)
    print("Copia exitosa. Usando el archivo local para el procesamiento de fase.")
except FileNotFoundError:
    print(f"❌ ERROR: El archivo de origen no se encontró en {ARCHIVO_INPUT}. Asegùrate de que exista en tu Drive.")
    exit()
except Exception as e:
    print(f"❌ Ocurrió un error al copiar el archivo: {e}")
    exit()
# ---------------------------------------------------------------------

# Load the entire original audio file once (Instruction 2) from the local path
print(f"Loading entire original audio for phase correction from: {LOCAL_TEMP_ORIGINAL_AUDIO_PATH}")
y_original_stereo, sr_original = librosa.load(LOCAL_TEMP_ORIGINAL_AUDIO_PATH, sr=None, mono=False)
print(f"✅ Original audio loaded. Shape: {y_original_stereo.shape}, Sample Rate: {sr_original} Hz")

# Calculate samples per chunk after loading sr_original
samples_per_chunk = int(sr_original * chunk_duration_seconds)
print(f"Processing in chunks of {chunk_duration_seconds} seconds ({samples_per_chunk} samples).")

# Compute full STFTs and phase difference array for the entire audio once (Instruction 3)
print("1. Computing full STFT for left and right channels...")
stft_left_orig_full = librosa.stft(y_original_stereo[0], n_fft=n_fft, hop_length=hop_length)
stft_right_orig_full = librosa.stft(y_original_stereo[1], n_fft=n_fft, hop_length=hop_length)

print("2. Calculating instantaneous phase for both full channels...")
phase_left_orig_full = np.angle(stft_left_orig_full)
phase_right_orig_full = np.angle(stft_right_orig_full)

print("3. Computing the full phase difference array...")
phase_difference_array_full = phase_left_orig_full - phase_right_orig_full
print(f"✅ Full phase difference array computed. Shape: {phase_difference_array_full.shape}")

print(f"Starting chunk-based phase correction with priority channel: {PHASE_CORRECTION_PRIORITY_CHANNEL}")

output_filename = "Phase_Corrected_Audio_Chunked.wav"
output_path = os.path.join(OUTPUT_FOLDER_PHASE_CORRECTIONS, output_filename)

# Open the output WAV file in write mode using soundfile (Instruction 4)
# soundfile automatically handles creating the file with correct headers from the first write
with sf.SoundFile(output_path, 'w', sr_original, y_original_stereo.shape[0], format='WAV') as f_out:
    total_samples = y_original_stereo.shape[1]
    processed_samples = 0
    current_stft_frame_idx = 0

    # Implement a for loop to iterate through the audio in chunks (Instruction 5)
    for i in range(0, total_samples, samples_per_chunk):
        chunk_start_sample = i
        chunk_end_sample = min(i + samples_per_chunk, total_samples)
        current_chunk_sample_length = chunk_end_sample - chunk_start_sample

        if current_chunk_sample_length <= 0:
            continue

        # Extract the stereo audio chunk
        y_original_stereo_chunk = y_original_stereo[:, chunk_start_sample:chunk_end_sample]

        # Compute STFTs and their magnitudes/phases for the current chunk (Instruction 6)
        stft_left_chunk = librosa.stft(y_original_stereo_chunk[0], n_fft=n_fft, hop_length=hop_length)
        stft_right_chunk = librosa.stft(y_original_stereo_chunk[1], n_fft=n_fft, hop_length=hop_length)

        magnitude_left_chunk = np.abs(stft_left_chunk)
        magnitude_right_chunk = np.abs(stft_right_chunk)
        phase_left_chunk = np.angle(stft_left_chunk)
        phase_right_chunk = np.angle(stft_right_chunk)

        # Determine the number of frames for the current chunk's STFT
        n_frames_chunk = stft_left_chunk.shape[1]

        # Extract the corresponding phase_difference_array_chunk (Instruction 7)
        phase_difference_array_chunk = phase_difference_array_full[:, current_stft_frame_idx : current_stft_frame_idx + n_frames_chunk]

        # Ensure lengths match in case of slight discrepancies at the end of audio
        if phase_difference_array_chunk.shape[1] != n_frames_chunk:
            # This can happen if the last chunk is smaller than n_fft/hop_length calculation implies
            # Adjust phase_difference_array_chunk to match the actual frames of the current STFT
            phase_difference_array_chunk = librosa.util.fix_length(phase_difference_array_chunk, size=n_frames_chunk, axis=1)

        # Apply phase correction on the *_chunk variables (Instruction 8)
        corrected_phase_non_priority_chunk = None
        magnitude_non_priority_chunk = None
        corrected_stft_priority_chunk = None # To hold the original STFT for the priority channel

        if PHASE_CORRECTION_PRIORITY_CHANNEL == 'L':
            # Correct right channel's phase using the difference (L - R) as an offset to R's original phase
            corrected_phase_non_priority_chunk = phase_right_chunk + phase_difference_array_chunk
            magnitude_non_priority_chunk = magnitude_right_chunk
            corrected_stft_priority_chunk = stft_left_chunk # Left channel magnitude and phase unchanged

        elif PHASE_CORRECTION_PRIORITY_CHANNEL == 'R':
            # Correct left channel's phase using the difference (R - L) as an offset to L's original phase
            corrected_phase_non_priority_chunk = phase_left_chunk - phase_difference_array_chunk # Apply negative difference
            magnitude_non_priority_chunk = magnitude_left_chunk
            corrected_stft_priority_chunk = stft_right_chunk # Right channel magnitude and phase unchanged

        # Reconstruct STFT for the corrected non-priority channel
        corrected_stft_non_priority_chunk = magnitude_non_priority_chunk * np.exp(1j * corrected_phase_non_priority_chunk)

        # Perform Inverse STFT to convert back to time domain (Instruction 9)
        y_corrected_non_priority_chunk = librosa.istft(corrected_stft_non_priority_chunk, hop_length=hop_length, length=current_chunk_sample_length)

        # Also inverse STFT the priority channel (its magnitude and phase were kept)
        y_corrected_priority_chunk = librosa.istft(corrected_stft_priority_chunk, hop_length=hop_length, length=current_chunk_sample_length)

        # Combine the corrected channels into y_corrected_stereo_chunk (Instruction 10)
        y_corrected_stereo_chunk = np.empty((2, current_chunk_sample_length), dtype=y_original_stereo.dtype)
        if PHASE_CORRECTION_PRIORITY_CHANNEL == 'L':
            y_corrected_stereo_chunk[0] = y_corrected_priority_chunk
            y_corrected_stereo_chunk[1] = y_corrected_non_priority_chunk
        else: # PHASE_CORRECTION_PRIORITY_CHANNEL == 'R'
            y_corrected_stereo_chunk[0] = y_corrected_non_priority_chunk
            y_corrected_stereo_chunk[1] = y_corrected_priority_chunk

        # Write y_corrected_stereo_chunk to the output WAV file (Instruction 11)
        f_out.write(y_corrected_stereo_chunk.T)

        processed_samples += current_chunk_sample_length
        current_stft_frame_idx += n_frames_chunk

        print(f"   Processed {processed_samples / sr_original:.2f} / {total_samples / sr_original:.2f} seconds ({100 * processed_samples / total_samples:.2f}%)")

        # Release memory for chunk-specific variables (Instruction 12)
        del y_original_stereo_chunk, stft_left_chunk, stft_right_chunk, magnitude_left_chunk, magnitude_right_chunk, \
            phase_left_chunk, phase_right_chunk, phase_difference_array_chunk, corrected_phase_non_priority_chunk, \
            magnitude_non_priority_chunk, corrected_stft_non_priority_chunk, y_corrected_non_priority_chunk, \
            y_corrected_priority_chunk, corrected_stft_priority_chunk, y_corrected_stereo_chunk
        gc.collect()

print(f"✅ Phase correction completed and saved to {output_path}")

# Release memory for large full audio arrays (Instruction 13)
del y_original_stereo, stft_left_orig_full, stft_right_orig_full, phase_left_orig_full, phase_right_orig_full, phase_difference_array_full
gc.collect()

