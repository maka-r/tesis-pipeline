"""#### Sobre la detección de finales de nota (Offsets):

La detección de "offsets" (finales de nota) es generalmente más desafiante que la de "onsets". `librosa` no tiene una función directa y sencilla como `onset_detect` para los offsets.

Comúnmente, los offsets se pueden inferir de varias maneras:
1.  **Análisis de energía:** Buscando caídas significativas de energía después de un onset.
2.  **Segmentación:** Dividiendo el audio en segmentos donde cada segmento podría representar una nota, y luego los finales de esos segmentos serían los offsets.
3.  **Modelos más avanzados:** Usando técnicas de aprendizaje automático que han sido entrenadas para reconocer tanto el inicio como el final de los sonidos.

Si necesitas una detección precisa de offsets, se requeriría un procesamiento adicional que podría involucrar:
*   `librosa.effects.split()` para segmentar el audio basado en la energía.
*   Analizar el decaimiento de la energía o la envolvente de la señal después de cada onset.
"""

import librosa
import numpy as np

def detect_custom_offset(y_mono, sr, onset_sample, search_end_sample, threshold_ratio=0.05, min_frames_below_threshold=3):
    """
    Detecta el offset de una nota analizando su envolvente de energía (RMS).

    Args:
        y_mono (np.ndarray): El audio mono completo.
        sr (int): La tasa de muestreo del audio.
        onset_sample (int): El índice de muestra donde comienza la nota.
        search_end_sample (int): El índice de muestra hasta donde buscar el offset (ej. el siguiente onset o fin del audio).
        threshold_ratio (float): Proporción de la energía pico para establecer el umbral de offset.
        min_frames_below_threshold (int): Número mínimo de frames que la energía debe estar por debajo del umbral
                                          para considerar que el offset ha ocurrido.

    Returns:
        int: El índice de muestra estimado para el offset de la nota.
    """
    # Definir el segmento donde buscaremos el offset
    # Asegurarse de que el segmento de búsqueda no exceda los límites del audio
    search_segment_end = min(search_end_sample, len(y_mono))
    search_segment = y_mono[onset_sample:search_segment_end]

    if len(search_segment) == 0:
        return onset_sample # No hay audio en el segmento de búsqueda, el offset es el onset.

    # Parámetros para el cálculo de la energía RMS
    frame_length = 2048 # Tamaño de la ventana para FFT/análisis de energía
    hop_length = 512    # Paso para el cálculo de la energía

    # Si el segmento es demasiado corto para una trama, el offset es el final del segmento.
    if len(search_segment) < frame_length:
        return onset_sample + len(search_segment)

    # Calcular la energía RMS
    rms = librosa.feature.rms(y=search_segment, frame_length=frame_length, hop_length=hop_length)[0]

    if len(rms) == 0:
        return onset_sample # No se pudieron calcular frames RMS.

    # Encontrar la energía RMS pico en el segmento de búsqueda
    peak_rms = np.max(rms)
    if peak_rms == 0:
        return onset_sample + len(search_segment) # Evitar división por cero o umbral cero si el segmento es silencio

    # Calcular el umbral dinámico
    threshold = peak_rms * threshold_ratio

    # Buscar el primer frame donde la energía cae por debajo del umbral
    offset_frame = len(rms) - 1 # Por defecto, el offset es el final del segmento de búsqueda en frames
    found_sustained_drop = False

    for i in range(len(rms) - min_frames_below_threshold):
        if np.all(rms[i : i + min_frames_below_threshold] < threshold):
            offset_frame = i
            found_sustained_drop = True
            break

    # Si no se encuentra una caída sostenida, el offset puede ser el final del segmento
    # o un decaimiento muy gradual. En estos casos, usamos el final del segmento de búsqueda.
    if not found_sustained_drop:
        offset_frame = len(rms) - 1

    # Convertir el índice del frame de offset a un índice de muestra, relativo al inicio del search_segment
    offset_sample_in_search_segment = librosa.frames_to_samples(offset_frame, hop_length=hop_length)

    # Convertir a índice de muestra global en el audio original completo
    global_offset_sample = onset_sample + offset_sample_in_search_segment

    # Asegurarse de que el offset no exceda el límite del segmento de búsqueda
    global_offset_sample = min(global_offset_sample, search_end_sample)

    return int(global_offset_sample)

